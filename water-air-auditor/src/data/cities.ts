/**
 * Convenience: get a city by free-form name within a state. Case-insensitive
 * match on `name`. Returns null if no city is found in TOP_CITIES_BY_STATE.
 */
export function findCity(stateCode: string, name: string): CityEntry | null {
  const list = TOP_CITIES_BY_STATE[stateCode] || [];
  const target = name.trim().toLowerCase();
  return list.find((c) => c.name.toLowerCase() === target) ?? null;
}
